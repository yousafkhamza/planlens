// Builds every distributable from the same source:
//   dist/cli.mjs        npm bin (node >= 20)
//   dist/index.mjs      library API
//   dist/action.cjs     GitHub Action entry (committed; action.yml points here)
//   docs/assets/planlens.js  browser bundle for the GitHub Pages tool
//   dist/types          .d.ts for the library
import { execFileSync } from "node:child_process";
import { readFileSync, rmSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { build } from "esbuild";

const root = fileURLToPath(new URL("..", import.meta.url));
const pkg = JSON.parse(readFileSync(new URL("../package.json", import.meta.url), "utf8"));
const versionSrc = readFileSync(new URL("../src/version.ts", import.meta.url), "utf8");
if (!versionSrc.includes(`"${pkg.version}"`)) {
  console.error(`src/version.ts does not match package.json version ${pkg.version}`);
  process.exit(1);
}

rmSync(`${root}/dist`, { recursive: true, force: true });

const common = { bundle: true, minify: false, sourcemap: false, legalComments: "none", logLevel: "info", absWorkingDir: root };
const banner = "// planlens — https://github.com/yousafkhamza/planlens — MIT License";

await Promise.all([
  build({
    ...common,
    entryPoints: ["src/bin.ts"],
    outfile: "dist/cli.mjs",
    platform: "node",
    target: "node20",
    format: "esm",
    banner: { js: `#!/usr/bin/env node\n${banner}\nimport { createRequire as __cr } from "node:module"; const require = __cr(import.meta.url);` },
  }),
  build({ ...common, entryPoints: ["src/index.ts"], outfile: "dist/index.mjs", platform: "node", target: "node20", format: "esm", banner: { js: banner } }),
  build({
    ...common,
    entryPoints: ["src/action/entry.ts"],
    outfile: "dist/action.cjs",
    platform: "node",
    target: "node20",
    format: "cjs",
    banner: { js: banner },
  }),
  build({
    ...common,
    entryPoints: ["src/web.ts"],
    outfile: "docs/assets/planlens.js",
    platform: "browser",
    target: "es2020",
    format: "iife",
    minify: true,
    banner: { js: banner },
  }),
]);

execFileSync(process.execPath, [`${root}/node_modules/typescript/bin/tsc`, "-p", "tsconfig.build.json"], { stdio: "inherit", cwd: root });

// docs/rules.md is generated from the rule definitions so it can never drift.
const { RULES } = await import(new URL("../dist/index.mjs", import.meta.url).href);
const icon = { critical: "🔴", high: "🟠", medium: "🟡", low: "🔵", info: "⚪" };
const lines = [
  "# planlens rule reference",
  "",
  "<!-- Generated by scripts/build.mjs from src/core/rules — do not edit by hand. -->",
  "",
  `${RULES.length} built-in rules. Severities are defaults — change them with \`severity_overrides\`, turn rules off with \`disable\`, or accept a specific finding with \`ignore\` in \`.planlens.yml\`.`,
  "",
  "Most rules only report what **this plan introduces** (a new open port, a newly widened policy, protection switched off). Pre-existing debt is not re-reported on every PR.",
  "",
  "| ID | Default severity | Category | Rule |",
  "|---|---|---|---|",
  ...RULES.map((r) => `| [${r.id}](#${r.id.toLowerCase()}) | ${icon[r.severity]} ${r.severity} | ${r.category} | ${r.title} |`),
  "",
  ...RULES.flatMap((r) => [
    `<a id="${r.id.toLowerCase()}"></a>`,
    "",
    `## ${r.id} · ${r.title}`,
    "",
    `**Default severity:** ${icon[r.severity]} ${r.severity} · **Category:** ${r.category}`,
    "",
    r.description,
    "",
    `**Fix:** ${r.remediation}`,
    "",
  ]),
];
writeFileSync(`${root}/docs/rules.md`, `${lines.join("\n")}`);

// docs/rules.html — indexable rule reference for search engines (same source as rules.md).
